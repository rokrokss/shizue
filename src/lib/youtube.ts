export type TranscriptMetadata = {
  languageCode: string;
  isAutoGenerated: boolean;
  uiText: string;
  baseUrl: string;
  language: Language;
};

export type VideoMetadata = {
  title: string;
  duration: number;
  author: string;
  keywords: string[];
  shortDescription: string;
  channelId: string;
};

export type Caption = {
  startTime: number;
  endTime: number;
  text: string;
  // Speech recognition's own word timings: where each word starts in `text` and when it is said.
  words?: { offset: number; time: number }[];
};

// Live streams have no caption tracks to download: their captions come with the media and are
// read from the screen (lib/youtubeCaption).
export type LiveInfo = {
  isLive: boolean;
  // Only normal-latency streams can carry captions; no low-latency one did in testing.
  normalLatency: boolean;
  // The broadcaster's CEA-608 captions, or YouTube's speech recognition (kind 'asr').
  captionTrack?: { languageCode: string; kind?: string };
};

// Regex to parse the player response from the page
const YT_INITIAL_PLAYER_RESPONSE_RE =
  /ytInitialPlayerResponse\s*=\s*({.+?})\s*;\s*(?:var\s+(?:meta|head)|<\/script|\n)/;

function compareTracks(track1: any, track2: any) {
  const langCode1 = track1.languageCode;
  const langCode2 = track2.languageCode;

  if (track1.kind !== 'asr' && track2.kind === 'asr') {
    // asr: Automatic Speech Recognition
    return -1; // Non-ASR comes first
  } else if (track1.kind === 'asr' && track2.kind !== 'asr') {
    return 1; // Non-ASR comes first
  } else if (langCode1 === 'en' && langCode2 !== 'en') {
    return -1; // English comes first
  } else if (langCode1 !== 'en' && langCode2 === 'en') {
    return 1; // English comes first
  }

  return 0;
}

// A player another site embeds (youtube.com/embed/<id>, or youtube-nocookie.com/embed/<id>), in
// that site's frame.
export const isYoutubeEmbed = () =>
  /(^|\.)youtube(-nocookie)?\.com$/.test(location.hostname) && location.pathname.startsWith('/embed/');

// The title links to the video playing, in the embed's older controls and in its newer ones.
const EMBED_TITLE_LINK = 'a.ytp-title-link, a.ytmVideoInfoVideoTitle';

export const getVideoId = () => {
  if (!isYoutubeEmbed()) return new URLSearchParams(window.location.search).get('v');
  // An embed's playlist (/embed/videoseries?list=…) moves on without changing the address.
  const link = document.querySelector<HTMLAnchorElement>(EMBED_TITLE_LINK)?.href;
  const linked = link ? new URL(link).searchParams.get('v') : null;
  return linked ?? location.pathname.match(/^\/embed\/([\w-]{11})$/)?.[1] ?? null;
};

// YouTube fills its ad module while an ad plays.
export const isYoutubeAdPlaying = () => {
  const ad = document.querySelector<HTMLDivElement>('.ytp-ad-module');
  return !!ad && ((ad.textContent?.trim().length ?? 0) > 0 || ad.childElementCount > 0);
};

// The player's own timedtext request carries whatever this session needs to get captions
// (a pot token or not, depending on the account), so capture it whole instead of just the pot.
// Watching from the start means captions turned on earlier in the session spare the clicks below.
const playerCaptionUrls = new Map<string, string>();

export const watchPlayerCaptionRequests = () => {
  const observer = new PerformanceObserver((list) => {
    for (const entry of list.getEntries() as PerformanceResourceTiming[]) {
      // Skip our own caption fetches; the player requests them with XHR. A request it cancels (the
      // off click right after the on) went out without the pot token, so only finished ones count.
      if (!entry.name.includes('timedtext') || entry.initiatorType === 'fetch' || entry.responseStatus === 0) {
        continue;
      }
      const videoId = new URL(entry.name).searchParams.get('v');
      if (videoId) {
        debugLog('[Youtube] watchPlayerCaptionRequests: entry', entry);
        playerCaptionUrls.set(videoId, entry.name);
      }
    }
  });
  observer.observe({ type: 'resource', buffered: true });
  return () => observer.disconnect();
};

const getPlayerCaptionUrl = async (videoId: string): Promise<string | null> => {
  const knownUrl = playerCaptionUrls.get(videoId);
  if (knownUrl) return knownUrl;

  // No request for this video yet: toggle captions on and off so the player makes one. Both clicks
  // in the same task are enough for it, and the captions never show; a player that didn't ask
  // gets the clicks again a second later, apart.
  debugLog('[Youtube] getPlayerCaptionUrl: toggling captions for', videoId);
  const subtitlesButton = document.querySelector(SUBTITLES_BUTTON);
  if (subtitlesButton instanceof HTMLElement) {
    subtitlesButton.click();
    subtitlesButton.click();
  }

  for (let waited = 0; waited < 5000; waited += 50) {
    await new Promise((resolve) => setTimeout(resolve, 50));
    const url = playerCaptionUrls.get(videoId);
    if (url) return url;
    if (waited === 1000 && subtitlesButton instanceof HTMLElement) {
      subtitlesButton.click();
      setTimeout(() => subtitlesButton.click(), 200);
    }
  }
  return null;
};

// A video's tracks differ in lang, kind and sometimes variant (a dub's track has
// 'timing-optimized'), so swapping them (plus name/tlang) into the player's request keeps its
// auth params valid for any track.
const TRACK_PARAMS = ['lang', 'kind', 'variant', 'name', 'tlang'];

const buildCaptionUrl = (trackBaseUrl: string, playerCaptionUrl: string | null) => {
  if (!playerCaptionUrl) {
    const url = new URL(trackBaseUrl);
    url.searchParams.set('c', 'WEB');
    url.searchParams.set('fmt', 'json3');
    url.searchParams.set('cplatform', 'DESKTOP');
    return url.toString();
  }

  const url = new URL(playerCaptionUrl);
  const trackParams = new URL(trackBaseUrl).searchParams;
  for (const key of TRACK_PARAMS) {
    const value = trackParams.get(key);
    if (value === null) {
      url.searchParams.delete(key);
    } else {
      url.searchParams.set(key, value);
    }
  }
  url.searchParams.set('fmt', 'json3');
  return url.toString();
};

export const getCaptionUrl = async (trackBaseUrl: string) => {
  const videoId = new URL(trackBaseUrl).searchParams.get('v') ?? '';
  return buildCaptionUrl(trackBaseUrl, await getPlayerCaptionUrl(videoId));
};

// A caption track's lines, each ending where the next starts, or null when it can't be read.
// Speech recognition lines keep their word timings only when asked (`withWords`).
export const fetchCaptionTrack = async (
  metadata: TranscriptMetadata,
  withWords = false
): Promise<Caption[] | null> => {
  try {
    const response = await fetch(await getCaptionUrl(metadata.baseUrl));
    const data = await response.json();
    // Speech recognition comes in rolling fragments: put its words back into sentences.
    if (metadata.isAutoGenerated) {
      const sentences = groupAsrSentences(data.events);
      return withWords ? sentences : sentences.map(({ words: _words, ...caption }) => caption);
    }
    const captions: Caption[] = data.events
      .filter((event: any) => event.segs)
      .map((event: any) => ({
        startTime: event.tStartMs / 1000,
        endTime: (event.tStartMs + event.dDurationMs) / 1000,
        text: event.segs
          .map((seg: any) => seg.utf8)
          .join('')
          .trim(),
      }))
      .filter((caption: Caption) => caption.text.length > 0);

    return captions.map((caption, i) => {
      if (i === captions.length - 1) return caption;
      const nextCaption = captions[i + 1];
      return {
        ...caption,
        endTime: Math.min(caption.endTime, nextCaption.startTime),
      };
    });
  } catch (err) {
    errorLog(`[YouTube] Failed to fetch captions for ${metadata.language}`, err);
    return null;
  }
};

// The player data in a watch page.
export const parsePlayerResponse = (body: string) => {
  const playerResponseMatch = body.match(YT_INITIAL_PLAYER_RESPONSE_RE);
  return playerResponseMatch ? JSON.parse(playerResponseMatch[1]) : null;
};

// The player's own data for the video, from youtube-player-hook.content (page world), when it is
// that video's. It answers within the dispatch; embeds have no hook.
const pagePlayerResponse = (videoId: string) =>
  new Promise<any>((resolve) => {
    const finish = (response: any) => {
      clearTimeout(timer);
      window.removeEventListener(HOOK_TO_CONTENT_EVENT, onMessage);
      resolve(response);
    };
    const onMessage = (event: Event) => {
      const message = parseHookDetail<HookMessage>((event as CustomEvent).detail);
      if (message?.type !== 'playerResponse') return;
      const response: any = message.response;
      // Only with what the captions and the original language are read from.
      const complete = response?.videoDetails?.videoId === videoId && response.streamingData;
      finish(complete ? response : null);
    };
    const timer = setTimeout(() => finish(null), 200);
    window.addEventListener(HOOK_TO_CONTENT_EVENT, onMessage);
    const request: HookRequest = { type: 'playerResponse' };
    window.dispatchEvent(new CustomEvent(CONTENT_TO_HOOK_EVENT, { detail: JSON.stringify(request) }));
  });

const getPlayerData = async (videoId: string) => {
  // youtube-nocookie.com has no watch pages, and its frames may not read youtube.com's.
  if (location.hostname.endsWith('youtube-nocookie.com')) {
    return chrome.runtime.sendMessage({ action: MESSAGE_FETCH_YOUTUBE_PLAYER, videoId });
  }
  // The player already has it; fetching the watch page again (about 2 MB) takes most of a second.
  const inPage = isYoutubeEmbed() ? null : await pagePlayerResponse(videoId);
  if (inPage) return inPage;
  const pageData = await fetch(`https://www.youtube.com/watch?v=${videoId}`);
  return parsePlayerResponse(await pageData.text());
};

const toTranscriptMetadata = (track: any) =>
  ({
    languageCode: track.languageCode,
    isAutoGenerated: track.kind === 'asr',
    uiText: track.name?.simpleText ?? track.languageCode,
    baseUrl: track.baseUrl,
    language: languageCodeToLanguage(track.languageCode),
  }) as TranscriptMetadata;

const getTranscriptMetadata = async (
  player: any,
  originalLanguageCode: string | undefined
): Promise<TranscriptMetadata[] | undefined> => {
  try {
    const tracks: any[] | undefined =
      player?.captions?.playerCaptionsTracklistRenderer?.captionTracks;
    if (!tracks?.length) return;

    const sortedTracks = tracks.sort(compareTracks);

    // Without captions people wrote, the speech recognition track in the original language. A
    // dubbed video also has one per dub language, machine-translated from the original, and those
    // are never used.
    const filteredTracks = sortedTracks.filter((t: any) => t.kind != 'asr');
    if (!filteredTracks.length) {
      const originalLanguage = originalLanguageCode?.split('-')[0];
      const track = originalLanguage
        ? sortedTracks.find(
            (t: any) => t.kind === 'asr' && t.languageCode.split('-')[0] === originalLanguage
          )
        : sortedTracks[0];
      if (!track) return;
      filteredTracks.push(track);
    }

    return filteredTracks.map(toTranscriptMetadata);
  } catch (error) {
    errorLog('[Youtube] getTranscriptMetadata: error', error);
    return;
  }
};

// The language the video is spoken in. A video YouTube dubbed has an audio track per language, and
// the one not marked auto-dubbed is the original, its ID starting with its language ('ko.4').
// Otherwise YouTube's speech recognition track ('asr') is in it, and without one, a video's only
// caption track is taken to be.
const getOriginalLanguageCode = (player: any): string | undefined => {
  const audioTracks: any[] = (player?.streamingData?.adaptiveFormats ?? [])
    .map((format: any) => format.audioTrack)
    .filter(Boolean);
  const originals = new Set(
    audioTracks
      .filter((track) => !track.isAutoDubbed && track.id)
      .map((track) => track.id.split('.')[0] as string)
  );
  if (originals.size === 1) return [...originals][0];

  const tracks: any[] = player?.captions?.playerCaptionsTracklistRenderer?.captionTracks ?? [];
  const asr = tracks.find((track) => track.kind === 'asr');
  return asr?.languageCode ?? (tracks.length === 1 ? tracks[0].languageCode : undefined);
};

// The language the viewer hears, when the page settles it: with one audio track, the language
// YouTube's speech recognition heard. A dubbed video has a recognition track per audio language,
// and which one plays only the player knows (youtubeCaption/youtubePlatform.ts asks it).
const getSpokenLanguageCode = (player: any): string | undefined => {
  const renderer = player?.captions?.playerCaptionsTracklistRenderer;
  if ((renderer?.audioTracks?.length ?? 0) > 1) return;
  const asr: any[] = (renderer?.captionTracks ?? []).filter((track: any) => track.kind === 'asr');
  return asr.length === 1 ? asr[0].languageCode : undefined;
};

// The captions bilingual mode shows over a target language's own track: the original language's
// captions people wrote, else its speech recognition track (never a dub's).
const getOriginalTrack = (player: any, originalLanguageCode: string | undefined) => {
  const originalLanguage = originalLanguageCode?.split('-')[0];
  if (!originalLanguage) return;
  const tracks: any[] = (
    player?.captions?.playerCaptionsTracklistRenderer?.captionTracks ?? []
  ).filter((track: any) => track.languageCode.split('-')[0] === originalLanguage);
  const track = tracks.find((t) => t.kind !== 'asr') ?? tracks[0];
  return track ? toTranscriptMetadata(track) : undefined;
};

const getLiveInfo = (player: any): LiveInfo => {
  const latencyClass: string | undefined = player?.videoDetails?.latencyClass;
  const captionTrack = player?.streamingData?.adaptiveFormats?.find((f: any) => f.captionTrack)?.captionTrack;
  return {
    isLive: !!player?.videoDetails?.isLive,
    normalLatency: !!latencyClass?.endsWith('LATENCY_NORMAL'),
    captionTrack: captionTrack?.languageCode
      ? { languageCode: captionTrack.languageCode, kind: captionTrack.kind }
      : undefined,
  };
};

export const getVideoData = async (videoId: string) => {
  const player = await getPlayerData(videoId);
  if (!player) {
    errorLog('[Youtube] getVideoData: Unable to get player data');
    return { videoId };
  }
  const live = getLiveInfo(player);
  const metadata: VideoMetadata = {
    title: player.videoDetails.title,
    duration: player.videoDetails.lengthSeconds,
    author: player.videoDetails.author,
    keywords: player.videoDetails.keywords,
    shortDescription: player.videoDetails.shortDescription,
    channelId: player.videoDetails.channelId,
  };

  // The seek bar's preview frames (lib/storyboard.ts). Short videos have none.
  const storyboard: string | undefined = player.storyboards?.playerStoryboardSpecRenderer?.spec;

  debugLog('[Youtube] getVideoData: player', player);
  // Read before getTranscriptMetadata sorts the tracks English first.
  const originalLanguageCode = getOriginalLanguageCode(player);
  const spokenLanguageCode = getSpokenLanguageCode(player);
  const transcriptMetadata = await getTranscriptMetadata(player, originalLanguageCode);
  if (!transcriptMetadata) {
    debugLog('[Youtube] getVideoData: No transcript data found');
    return { videoId, metadata, live, storyboard, spokenLanguageCode };
  }

  const originalTrack = getOriginalTrack(player, originalLanguageCode);
  return {
    videoId,
    metadata,
    transcriptMetadata,
    live,
    originalLanguageCode,
    originalTrack,
    storyboard,
    spokenLanguageCode,
  };
};
